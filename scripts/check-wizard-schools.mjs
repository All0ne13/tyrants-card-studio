import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const { chromium } = createRequire(import.meta.url)('C:/Users/Vladislav/node_modules/playwright');
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.CARD_STUDIO_URL || 'http://127.0.0.1:4188/');
  const schoolField = page.locator('[data-key="secondaryAspectText"]');
  await schoolField.waitFor({ state: 'visible' });
  assert.ok(await schoolField.isVisible(), 'Original school presets are visible without opening a disclosure');
  assert.equal(await page.locator('[data-key="secondaryAspectSymbol"]').count(), 0);
  assert.doesNotMatch(await page.locator('[data-key="rulesHeight"]').innerText(), /Gremlin|Huntman/);
  for (const school of ['abjuration', 'necromancy', 'illusion', 'enchantment', 'evocation', 'divination', 'conjuration', 'transmutation', 'any']) {
    await page.locator(`[data-arcane-school="${school}"]`).click();
    await page.waitForFunction(id => document.querySelector(`[data-arcane-school="${id}"]`)?.getAttribute('aria-pressed') === 'true', school);
    assert.ok(await schoolField.inputValue());
  }
  await page.locator('[data-key="name"]').fill('Prodigious Novice Arcanist');
  await page.locator('[data-key="type"]').fill('Wizard');
  await page.locator('[data-key="aspectText"]').fill('Obedience');
  await page.locator('[data-key="cost"]').fill('2');
  await page.locator('[data-key="deckVP"]').fill('');
  await page.locator('[data-variable-points="deckVP"]').click();
  await page.locator('[data-key="innerVP"]').fill('2');
  await page.locator('[data-variable-points="innerVP"]').click();
  assert.equal(await page.locator('[data-key="innerVP"]').inputValue(), '2*');
  await page.locator('[data-key="secondaryAspectOffsetY"]').fill('-4');
  await page.locator('[data-deck-mark="wizards"]').click();
  await page.waitForTimeout(800);
  await page.reload();
  assert.equal(await schoolField.inputValue(), 'Any Arcana');
  assert.equal(await page.locator('[data-key="deckVP"]').inputValue(), '*');
  assert.equal(await page.locator('[data-key="secondaryAspectOffsetY"]').inputValue(), '-4');
  await page.getByText('Custom icon', {exact: true}).click();
  await page.locator('[data-reset-school-icon]').click();
  const download = page.waitForEvent('download');
  await page.locator('[data-export="png"]').click();
  const file = await download;
  await file.saveAs('.preview/wizards-school-export.png');
  await schoolField.evaluate(node => node.closest('details').open = true);
  await page.screenshot({ path: '.preview/wizards-original-schools.png', fullPage: true });
  await page.goto((process.env.CARD_STUDIO_URL || 'http://127.0.0.1:4188/') + '#library/mercenaries');
  assert.equal(await page.locator('.translation-downloads a').count(), 1);
  assert.match(await page.locator('.translation-downloads').innerText(), /Marcos Otaviano/);
  await page.goto((process.env.CARD_STUDIO_URL || 'http://127.0.0.1:4188/') + '#library/siege');
  assert.equal(await page.locator('.translation-downloads a').count(), 2);
  assert.deepEqual(errors, []);
  console.log('Visible original presets, clean labels, text position, star buttons, PNG export and translation source links passed.');
} finally { await browser.close(); }
